"""Check that Hire publishes the exact CV uploaded by the user on Nov 10, 2026.

This document must never be rewritten or regenerated by this repository.
"""
from pathlib import Path
from hashlib import sha256
import fitz

pdf = Path(__file__).resolve().parents[1] / "dist/hire/assets/Eugen_Skaromny_CV.pdf"
assert pdf.exists(), "Original CV not in dist/hire/assets — copy assets/Eugen_Skaromny_CV.pdf"
data = pdf.read_bytes()
expected = "d3fd77b3e1e84bb3e9c55d5084acad308de203b45aae838e2f171e0da23b1896"
assert sha256(data).hexdigest() == expected, "PDF is not the user's exact November 10 original"
document = fitz.open(pdf)
assert document.page_count == 3, "User's original CV has three pages, not two"

text = "\n".join(page.get_text() for page in document)
for phrase in ("YAUHENI SKAROMNY", "VODAFONE", "MEGAFON", "PINKMAN",
               "CREATIVEPEOPLE", "16M", "10,000", "7M", "2015"):
    assert phrase in text, f"Original CV is missing the expected text: {phrase}"
output = pdf.parents[3] / "artifacts/screenshots"
output.mkdir(parents=True, exist_ok=True)
for n, page in enumerate(document, 1):
    page.get_pixmap(matrix=fitz.Matrix(1.35, 1.35), alpha=False).save(output / f"cv-original-{n}.png")
print("PASS exact original uploaded CV, 3 pages, sha256 " + expected[:16] + "...")
